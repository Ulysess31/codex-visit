-- 공개 방문자가 읽고 새 글·댓글을 남길 수 있도록 하는 전자 방명록 스키마.
-- 공개 읽기와 비로그인 쓰기가 활성화되므로 배포 전에 프로젝트 운영자가 정책을 검토해야 합니다.

alter table public.guestbook
  add column if not exists media_path text,
  add column if not exists media_kind text;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'guestbook_media_kind_check'
      and conrelid = 'public.guestbook'::regclass
  ) then
    alter table public.guestbook
      add constraint guestbook_media_kind_check
      check (media_kind is null or media_kind in ('photo', 'drawing'));
  end if;
end $$;

create table if not exists public.guestbook_comments (
  id bigint generated by default as identity primary key,
  guestbook_id bigint not null references public.guestbook(id) on delete cascade,
  author text not null check (char_length(trim(author)) between 1 and 40),
  content text not null check (char_length(trim(content)) between 1 and 500),
  created_at timestamptz not null default now()
);

create index if not exists guestbook_comments_guestbook_created_idx
  on public.guestbook_comments (guestbook_id, created_at);

alter table public.guestbook enable row level security;
alter table public.guestbook_comments enable row level security;

drop policy if exists guestbook_public_read on public.guestbook;
create policy guestbook_public_read on public.guestbook
  for select to anon, authenticated using (true);

drop policy if exists guestbook_public_insert on public.guestbook;
create policy guestbook_public_insert on public.guestbook
  for insert to anon, authenticated
  with check (
    author is not null
    and char_length(trim(author)) between 1 and 40
    and (
      (content is not null and char_length(trim(content)) between 1 and 500)
      or (media_path is not null and media_kind in ('photo', 'drawing'))
    )
    and (
      (media_path is null and media_kind is null)
      or (media_path like 'entries/%' and media_kind in ('photo', 'drawing'))
    )
  );

drop policy if exists guestbook_comments_public_read on public.guestbook_comments;
create policy guestbook_comments_public_read on public.guestbook_comments
  for select to anon, authenticated using (true);

drop policy if exists guestbook_comments_public_insert on public.guestbook_comments;
create policy guestbook_comments_public_insert on public.guestbook_comments
  for insert to anon, authenticated
  with check (
    char_length(trim(author)) between 1 and 40
    and char_length(trim(content)) between 1 and 500
    and exists (
      select 1 from public.guestbook entry where entry.id = guestbook_id
    )
  );

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('guestbook-media', 'guestbook-media', true, 5242880, array['image/jpeg', 'image/png', 'image/webp', 'image/gif'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists guestbook_media_public_read on storage.objects;
create policy guestbook_media_public_read on storage.objects
  for select to anon, authenticated using (bucket_id = 'guestbook-media');

drop policy if exists guestbook_media_public_insert on storage.objects;
create policy guestbook_media_public_insert on storage.objects
  for insert to anon, authenticated
  with check (
    bucket_id = 'guestbook-media'
    and (storage.foldername(name))[1] = 'entries'
  );

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'guestbook'
    ) then
      alter publication supabase_realtime add table public.guestbook;
    end if;
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'guestbook_comments'
    ) then
      alter publication supabase_realtime add table public.guestbook_comments;
    end if;
  end if;
end $$;
